// Generates lib/src/link_stages.g.dart, the link builder stages for 0 to 20
// values (ADR 0004 D21). Run from packages/reef_router:
//   dart tool/generate_link_stages.dart
// A test compares the committed file with this output.
import 'dart:io';

const maxValues = 20;

String generate() {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_link_stages.dart. Do not edit.')
    ..writeln()
    ..writeln("part of 'links.dart';");
  for (var n = 0; n <= maxValues; n++) {
    final vs = [for (var i = 1; i <= n; i++) 'V$i'];
    String stage(List<String> values) => values.isEmpty
        ? 'Link<R>'
        : 'Link${values.length}<R, ${values.join(', ')}>';
    final self = stage(vs);
    final next = stage([...vs, 'V']);
    final nextRest = stage([...vs, 'List<String>']);
    out
      ..writeln()
      ..writeln('/// A link to [R] being built, holding $n value(s).')
      ..writeln('final class $self {');
    if (n == 0) {
      out
        ..writeln('  /// Starts at [path], literal segments split by `/`.')
        ..writeln('  Link(String path) : _parts = _literals(path);')
        ..writeln()
        ..writeln('  /// Mounts under a parent link to [P], read by [get]; the')
        ..writeln('  /// parent value is the first constructor parameter.')
        ..writeln('  Link1<R, P> parent<P>(P Function(R route) get) =>')
        ..writeln('      Link1._([..._parts, _parent(get)]);')
        ..writeln();
    }
    out.writeln('  const ${_ctor(n)}(this._parts);');
    out
      ..writeln()
      ..writeln('  final List<_Part> _parts;')
      ..writeln()
      ..writeln('  /// Adds the literal path segment [text].')
      ..writeln('  $self literal(String text) =>')
      ..writeln('      ${_ctor(n)}([..._parts, _Literal(text)]);');
    if (n < maxValues) {
      out
        ..writeln()
        ..writeln('  /// Adds a path segment read by [get], in [codec] or the')
        ..writeln('  /// codec inferred from [V].')
        ..writeln(
          '  $next field<V>(V Function(R route) get, {LinkCodec<V>? codec}) =>',
        )
        ..writeln('      ${_ctor(n + 1)}([..._parts, _field(get, codec)]);')
        ..writeln()
        ..writeln(
          '  /// Adds the query argument [name] read by [get]; [fallback]',
        )
        ..writeln(
          '  /// stands for an absent argument and is left out of the URL.',
        )
        ..writeln('  $next query<V>(')
        ..writeln('    String name,')
        ..writeln('    V Function(R route) get, {')
        ..writeln('    required V fallback,')
        ..writeln('    LinkCodec<V>? codec,')
        ..writeln('  }) =>')
        ..writeln(
          '      ${_ctor(n + 1)}([..._parts, _query(name, get, fallback, codec)]);',
        )
        ..writeln()
        ..writeln('  /// Adds a rest part: every remaining path segment.')
        ..writeln('  $nextRest rest(List<String> Function(R route) get) =>')
        ..writeln('      ${_ctor(n + 1)}([..._parts, _rest(get)]);');
    }
    final args = [for (var i = 0; i < n; i++) 'v[$i] as ${vs[i]}'].join(', ');
    out
      ..writeln()
      ..writeln('  /// The link, building its route with [create].')
      ..writeln('  TypedLink<R> build(R Function(${vs.join(', ')}) create) =>')
      ..writeln('      TypedLink._(_parts, (v) => create($args));')
      ..writeln('}');
  }
  return out.toString();
}

String _ctor(int n) => n == 0 ? 'Link._' : 'Link$n._';

void main() => File('lib/src/link_stages.g.dart').writeAsStringSync(generate());
