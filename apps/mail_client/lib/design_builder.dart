// build_runner builder for the design's Dart sources, from the files under
// design/: tokens.json -> lib/src/tokens.g.dart, the `Icon / *` components of
// SPEC.snapshot.json -> lib/src/icons.g.dart. Rerun after a design sync:
//
//   dart run build_runner build
import 'dart:convert';

// build and dart_style are dev dependencies: only build_runner loads this
// file.
// ignore_for_file: depend_on_referenced_packages
import 'package:build/build.dart';
import 'package:dart_style/dart_style.dart';

Builder designBuilder(BuilderOptions _) => _DesignBuilder();

class _DesignBuilder implements Builder {
  @override
  final buildExtensions = const {
    '^design/tokens.json': ['lib/src/tokens.g.dart'],
    '^design/SPEC.snapshot.json': ['lib/src/icons.g.dart'],
  };

  @override
  Future<void> build(BuildStep step) async {
    final json = jsonDecode(await step.readAsString(step.inputId));
    final tokens = step.inputId.path.endsWith('tokens.json');
    final source = tokens ? _tokens(json) : _icons(json);
    await step.writeAsString(
      step.allowedOutputs.single,
      DartFormatter(languageVersion: DartFormatter.latestLanguageVersion)
          .format(source),
    );
  }
}

const _header =
    '// GENERATED by lib/design_builder.dart from design/. Do not edit.\n';

/// `surface/nav` -> `surfaceNav`, `space/2` -> `space2`.
String _name(List<String> path) => [
  path.first,
  for (final p in path.skip(1)) p[0].toUpperCase() + p.substring(1),
].join();

String _tokens(Map<String, dynamic> json) {
  final out = StringBuffer(_header)
    ..writeln("import 'dart:ui';\n")
    ..writeln('/// The design tokens (design/tokens.json), named after their')
    ..writeln('/// design paths.')
    ..writeln('abstract final class MailTokens {');
  void walk(Map<String, dynamic> node, List<String> path) {
    if (node[r'$value'] case final value?) {
      out.writeln('  /// `${path.join('/')}`');
      final name = _name(path);
      switch (node[r'$type']) {
        case 'color':
          final hex = (value['hex'] as String).substring(1);
          out.writeln('  static const $name = Color(0xFF$hex);');
        case 'dimension':
          out.writeln('  static const double $name = ${value['value']};');
        case final type:
          throw UnsupportedError('token type $type at ${path.join('/')}');
      }
      return;
    }
    for (final MapEntry(:key, :value) in node.entries) {
      if (!key.startsWith(r'$')) walk(value, [...path, key]);
    }
  }

  walk(json, []);
  return (out..writeln('}')).toString();
}

String _icons(Map<String, dynamic> snapshot) {
  final out = StringBuffer(_header)
    ..writeln("import 'dart:ui';\n")
    ..writeln('/// The `Icon / *` glyphs (20x20 frame), as stroke paths.')
    ..writeln('enum MailGlyph {');
  final glyphs = <String>[], paths = StringBuffer();
  for (final MapEntry(:key, :value) in snapshot.entries) {
    if (!key.startsWith('component:Icon / ')) continue;
    final name = _name(key.substring('component:Icon / '.length).split('-'));
    final ops = <String>[];
    for (final child in value['data']['children'] as List) {
      _node(child, _identity, ops);
    }
    glyphs.add('  /// ${value['data']['description']}\n  $name(_$name)');
    paths.writeln(
      '\nPath _$name() => Path()\n${ops.map((o) => '  ..$o').join('\n')};',
    );
  }
  return (out
        ..writeln('${glyphs.join(',\n')};\n')
        ..writeln('  const MailGlyph(this.build);\n')
        ..writeln('  /// The glyph in its 20x20 frame.')
        ..writeln('  final Path Function() build;\n')
        ..writeln(
          '  /// Every glyph strokes at this width, round caps and joins.',
        )
        ..writeln('  static const strokeWidth = 1.6666666269302368;')
        ..writeln('}')
        ..write(paths))
      .toString();
}

typedef _M = List<double>; // [a, b, c, d, e, f]: x' = ax + cy + e

const _M _identity = [1, 0, 0, 1, 0, 0];

_M _mul(_M p, _M c) => [
  p[0] * c[0] + p[2] * c[1],
  p[1] * c[0] + p[3] * c[1],
  p[0] * c[2] + p[2] * c[3],
  p[1] * c[2] + p[3] * c[3],
  p[0] * c[4] + p[2] * c[5] + p[4],
  p[1] * c[4] + p[3] * c[5] + p[5],
];

String _pt(_M m, num x, num y) =>
    '${_f(m[0] * x + m[2] * y + m[4])}, ${_f(m[1] * x + m[3] * y + m[5])}';

String _f(num v) => double.parse(v.toStringAsFixed(4)).toString();

void _node(Map<String, dynamic> n, _M parent, List<String> ops) {
  final t = (n['transform'] as List?)?.cast<num>().map((v) => v.toDouble());
  final m = t == null ? parent : _mul(parent, t.toList());
  final w = (n['width'] as num).toDouble(), h = (n['height'] as num).toDouble();
  switch (n['type']) {
    case 'group':
      for (final c in n['children'] as List) {
        _node(c, m, ops);
      }
    case 'rectangle':
      // Only translations reach rectangles and ellipses in these glyphs.
      final r = (n['corners']?['radii'] as List?)?.first ?? 0;
      ops.add(
        'addRRect(RRect.fromLTRBR(${_pt(m, 0, 0)}, ${_pt(m, w, h)}, '
        'const Radius.circular(${_f(r)})))',
      );
    case 'ellipse':
      ops.add('addOval(Rect.fromLTRB(${_pt(m, 0, 0)}, ${_pt(m, w, h)}))');
    case 'line':
      ops
        ..add('moveTo(${_pt(m, 0, 0)})')
        ..add('lineTo(${_pt(m, w, 0)})');
    case 'vector':
      final net = n['network'] as Map<String, dynamic>;
      final v = (net['vertices'] as List).cast<Map<String, dynamic>>();
      int? last;
      for (final s in (net['segments'] as List).cast<Map<String, dynamic>>()) {
        final a = s['a'] as int, b = s['b'] as int;
        final ta = (s['ta'] as List).cast<num>();
        final tb = (s['tb'] as List).cast<num>();
        final (ax, ay) = (v[a]['x'] as num, v[a]['y'] as num);
        final (bx, by) = (v[b]['x'] as num, v[b]['y'] as num);
        if (last != a) ops.add('moveTo(${_pt(m, ax, ay)})');
        final straight = ta.every((c) => c == 0) && tb.every((c) => c == 0);
        ops.add(
          straight
              ? 'lineTo(${_pt(m, bx, by)})'
              : 'cubicTo(${_pt(m, ax + ta[0], ay + ta[1])}, '
                    '${_pt(m, bx + tb[0], by + tb[1])}, ${_pt(m, bx, by)})',
        );
        last = b;
      }
    case final type:
      throw UnsupportedError('icon node type $type');
  }
}
