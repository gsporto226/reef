// Generates lib/src/tokens.g.dart from design/tokens.json. Rerun after a
// design sync (test/tokens_test.dart fails until you do):
//
//   fvm dart run tool/tokens.dart
import 'dart:convert';
import 'dart:io';

const input = 'design/tokens.json', output = 'lib/src/tokens.g.dart';

/// The Dart source for [json], LF line endings, already dart-formatted.
String tokensSource(String json) {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/tokens.dart from $input. Do not edit.')
    ..writeln("import 'dart:ui';")
    ..writeln()
    ..writeln('/// The design tokens, named after their design paths.')
    ..writeln('abstract final class T {');
  var first = true;
  void walk(Map<String, dynamic> node, List<String> path) {
    if (node[r'$value'] case final Map<String, dynamic> value) {
      final name = [
        path.first,
        for (final p in path.skip(1)) p[0].toUpperCase() + p.substring(1),
      ].join();
      if (!first) out.writeln();
      first = false;
      out.writeln('  /// `${path.join('/')}`');
      switch (node[r'$type']) {
        case 'color':
          final alpha = ((value['alpha'] as num? ?? 1) * 255).round();
          final hex = (value['hex'] as String).substring(1);
          final argb = alpha.toRadixString(16).padLeft(2, '0') + hex;
          out.writeln('  static const $name = Color(0x${argb.toUpperCase()});');
        case 'dimension':
          out.writeln('  static const double $name = ${value['value']};');
        case final type:
          throw UnsupportedError('token type $type at ${path.join('/')}');
      }
      return;
    }
    for (final MapEntry(:key, :value) in node.entries) {
      if (key.startsWith(r'$')) continue;
      walk(value as Map<String, dynamic>, [...path, key]);
    }
  }

  walk(jsonDecode(json) as Map<String, dynamic>, []);
  return (out..writeln('}')).toString();
}

void main() =>
    File(output)
        .writeAsStringSync(tokensSource(File(input).readAsStringSync()));
